#ROC Curve
from sklearn.metrics import roc_curve, auc

def plot_roc(model, X_test, y_test, name):
    probs = model.predict_proba(X_test)[:,1]
    fpr, tpr, _ = roc_curve(y_test, probs)
    roc_auc = auc(fpr, tpr)

    plt.plot(fpr, tpr, label=f"{name} (AUC={roc_auc:.2f})")

# Plot all
